-- 실습용 예제 데이터베이스 (교안·앱·실습 문제가 모두 이 데이터를 쓴다)
-- DEPT(부서) 4건, EMP(사원) 14건, SALGRADE(급여 등급) 5건, DUAL(오라클의 1행짜리 테이블 흉내)
CREATE TABLE DEPT (
  DEPTNO  INTEGER PRIMARY KEY,          -- 부서 번호
  DNAME   VARCHAR(14) NOT NULL,         -- 부서 이름
  LOC     VARCHAR(13)                   -- 위치
);
CREATE TABLE EMP (
  EMPNO    INTEGER PRIMARY KEY,         -- 사원 번호
  ENAME    VARCHAR(10) NOT NULL,        -- 이름
  JOB      VARCHAR(9),                  -- 업무
  MGR      INTEGER,                     -- 관리자 사원 번호 (자기 참조)
  HIREDATE DATE,                        -- 입사일
  SAL      NUMERIC(7,2),                -- 급여
  COMM     NUMERIC(7,2),                -- 커미션 (없으면 NULL)
  DEPTNO   INTEGER REFERENCES DEPT(DEPTNO)
);
CREATE TABLE SALGRADE (GRADE INTEGER, LOSAL NUMERIC, HISAL NUMERIC);
CREATE TABLE DUAL (DUMMY CHAR(1));
